package app.logdate

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Embeds the JSON files of a client conformance fixture folder in a Kotlin object, so tests in
 * `commonTest` can read them on every target, iOS included, without a file system. The fixtures
 * stay the single source of truth: this copies them at build time and nothing generated is
 * checked in.
 *
 * ```kotlin
 * val fixtures = tasks.register<GenerateConformanceFixtures>("generateSealedConformanceFixtures") {
 *     fixtures.set(rootProject.layout.projectDirectory.dir("conformance/sealed"))
 *     packageName.set("app.logdate.space")
 *     objectName.set("SealedConformanceFixtures")
 *     outputDirectory.set(layout.buildDirectory.dir("generated/conformance/kotlin"))
 * }
 * kotlin.sourceSets.commonTest { kotlin.srcDir(fixtures.flatMap { it.outputDirectory }) }
 * ```
 */
@CacheableTask
abstract class GenerateConformanceFixtures : DefaultTask() {
    /** The folder whose top-level `.json` files are embedded. Subfolders are ignored. */
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val fixtures: DirectoryProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val objectName: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val files =
            fixtures
                .get()
                .asFile
                .listFiles { file -> file.isFile && file.extension == "json" }
                .orEmpty()
                .sortedBy { it.name }
                .associate { it.name to it.readText() }
        check(files.isNotEmpty()) { "No .json fixtures in ${fixtures.get().asFile}" }

        val output = outputDirectory.get().asFile.resolve(packageName.get().replace('.', '/'))
        output.deleteRecursively()
        output.mkdirs()
        output.resolve("${objectName.get()}.kt").writeText(conformanceFixtureSource(packageName.get(), objectName.get(), files))
    }
}

/** The Kotlin source of an object holding each of [files] (name to text) as a string constant. */
fun conformanceFixtureSource(
    packageName: String,
    objectName: String,
    files: Map<String, String>,
): String =
    buildString {
        appendLine("// Generated by GenerateConformanceFixtures from the conformance fixtures. Do not edit.")
        appendLine("package $packageName")
        appendLine()
        appendLine("internal object $objectName {")
        appendLine("    private val files: Map<String, String> =")
        appendLine("        mapOf(")
        files.forEach { (name, text) -> appendLine("            ${kotlinString(name)} to ${kotlinString(text)},") }
        appendLine("        )")
        appendLine()
        appendLine("    /** The text of the fixture file called [name], such as `padding.json`. */")
        appendLine("    fun text(name: String): String = files[name] ?: error(\"No conformance fixture called \$name\")")
        appendLine("}")
    }

/** [text] as a Kotlin string literal, escaped so it compiles to exactly [text]. */
internal fun kotlinString(text: String): String =
    buildString {
        append('"')
        for (char in text) {
            when {
                char == '\\' -> append("\\\\")
                char == '"' -> append("\\\"")
                char == '$' -> append("\\$")
                char == '\n' -> append("\\n")
                char == '\r' -> append("\\r")
                char == '\t' -> append("\\t")
                char.code in PRINTABLE_ASCII -> append(char)
                else -> append("\\u").append(char.code.toString(HEX_RADIX).padStart(UNICODE_ESCAPE_DIGITS, '0'))
            }
        }
        append('"')
    }

private val PRINTABLE_ASCII = 0x20..0x7e
private const val HEX_RADIX = 16
private const val UNICODE_ESCAPE_DIGITS = 4
