/**
 * The shared client conformance fixtures in `conformance/sealed/`, which the Mac and Linux apps
 * run as well. They are generated by `tools/lexicon-check/conformance.mjs`; the build embeds them
 * in [SealedConformanceFixtures].
 */
internal object ConformanceFixtures {
    /** The version of the suite's file shapes this module understands. */
    const val SUPPORTED_VERSION = 1

    /** The sealed fixture files this module reads, which must be all the manifest lists under `sealed/`. */
    val sealedFiles: List<String> = listOf("sealed/envelopes.json", "sealed/key-schedule.json", "sealed/padding.json")

    val manifest: JsonObject = parse("manifest.json")
    val keySchedule: JsonObject = parse("sealed/key-schedule.json")
    val padding: JsonObject = parse("sealed/padding.json")
    val envelopes: List<JsonObject> = parse("sealed/envelopes.json").list("envelopes")

    private fun parse(name: String): JsonObject = Json.parseToJsonElement(SealedConformanceFixtures.text(name)).jsonObject
}

internal fun JsonElement.text(): String = jsonPrimitive.content

internal fun JsonElement.string(key: String): String = jsonObject.getValue(key).text()

internal fun JsonElement.int(key: String): Int = jsonObject.getValue(key).jsonPrimitive.int

internal fun JsonElement.obj(key: String): JsonObject = jsonObject.getValue(key).jsonObject

internal fun JsonElement.ints(key: String): List<Int> = jsonObject.getValue(key).jsonArray.map { it.jsonPrimitive.int }

internal fun JsonElement.list(key: String): List<JsonObject> = jsonObject.getValue(key).jsonArray.map { it.jsonObject }

internal fun ByteArray.toHex(): String = joinToString("") { (it.toInt() and 0xff).toString(16).padStart(2, '0') }

internal fun String.hexToBytes(): ByteArray = chunked(2).map { it.toInt(16).toByte() }.toByteArray()

internal suspend fun ByteArray.sha256Hex(): String =
    CryptographyProvider.Default
        .get(SHA256)
        .hasher()
        .hash(this)
        .toHex()

/**
 * [element] with the string at the `/`-separated path of each rule in [expand] replaced by the
 * rule's `repeat` written `times` times, which is how the fixtures write a payload too long to
 * spell out.
 */
internal fun expanded(
    element: JsonObject,
    expand: List<JsonObject>,
): JsonObject = expand.fold(element) { current, rule -> replaced(current, rule.string("path").split('/').drop(1), rule) as JsonObject }

private fun replaced(
    element: JsonElement,
    path: List<String>,
    rule: JsonObject,
): JsonElement {
    if (path.isEmpty()) return JsonPrimitive(rule.string("repeat").repeat(rule.int("times")))
    val node = element.jsonObject
    return JsonObject(node + (path.first() to replaced(node.getValue(path.first()), path.drop(1), rule)))
}
